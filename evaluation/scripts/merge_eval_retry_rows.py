#!/usr/bin/env python3
from __future__ import annotations

import argparse
from collections import Counter
from datetime import datetime, timezone
import json
from pathlib import Path


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Merge retry evaluation rows into an existing eval_results.jsonl.")
    parser.add_argument("--main", type=Path, required=True)
    parser.add_argument("--retry", type=Path, required=True)
    parser.add_argument("--backup", type=Path, required=True)
    parser.add_argument("--task-id", required=True)
    parser.add_argument("--mode", required=True)
    parser.add_argument("--expected-repeat-count", type=int, default=3)
    parser.add_argument("--summary", type=Path, default=None)
    return parser.parse_args()


def load_jsonl(path: Path) -> list[dict]:
    rows: list[dict] = []
    if not path.exists():
        return rows
    with path.open("r", encoding="utf-8") as handle:
        for line in handle:
            if line.strip():
                rows.append(json.loads(line))
    return rows


def write_jsonl(path: Path, rows: list[dict]) -> None:
    with path.open("w", encoding="utf-8") as handle:
        for row in rows:
            handle.write(json.dumps(row, ensure_ascii=False) + "\n")


def repeat_index(row: dict) -> int:
    try:
        return int(row.get("repeat_index") or 1)
    except Exception:
        return 1


def build_summary(rows: list[dict]) -> dict:
    overall = {"total": len(rows), "completed": 0, "failed": 0, "success": 0, "failure": 0, "per_status": {}}
    per_mode: dict[str, dict] = {}
    per_type: dict[str, dict] = {}
    for row in rows:
        status = str(row.get("evaluation_status") or "")
        mode = str(row.get("mode") or "")
        eval_type = str(row.get("evaluation_type") or "")
        predicted = row.get("predicted_label")
        overall["per_status"][status] = int(overall["per_status"].get(status, 0)) + 1
        overall["completed" if status == "completed" else "failed"] += 1
        if status == "completed":
            if predicted == 1:
                overall["success"] += 1
            elif predicted == 0:
                overall["failure"] += 1

        mode_stats = per_mode.setdefault(mode, {"total": 0, "completed": 0, "failed": 0, "success": 0, "failure": 0, "per_status": {}})
        mode_stats["total"] += 1
        mode_stats["per_status"][status] = int(mode_stats["per_status"].get(status, 0)) + 1
        mode_stats["completed" if status == "completed" else "failed"] += 1
        if status == "completed":
            if predicted == 1:
                mode_stats["success"] += 1
            elif predicted == 0:
                mode_stats["failure"] += 1

        type_stats = per_type.setdefault(eval_type, {"total": 0, "completed": 0, "failed": 0, "success": 0, "failure": 0, "per_status": {}})
        type_stats["total"] += 1
        type_stats["per_status"][status] = int(type_stats["per_status"].get(status, 0)) + 1
        type_stats["completed" if status == "completed" else "failed"] += 1
        if status == "completed":
            if predicted == 1:
                type_stats["success"] += 1
            elif predicted == 0:
                type_stats["failure"] += 1
    return {
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "overall": overall,
        "per_mode": per_mode,
        "per_type": per_type,
        "note": "Regenerated by merge_eval_retry_rows.py after retry merge.",
    }


def main() -> None:
    args = parse_args()
    main_rows = load_jsonl(args.main)
    retry_rows_all = load_jsonl(args.retry)
    retry_rows = [
        row
        for row in retry_rows_all
        if row.get("task_id") == args.task_id and row.get("mode") == args.mode
    ]
    retry_by_repeat = {repeat_index(row): row for row in retry_rows}
    missing_repeats = [idx for idx in range(1, args.expected_repeat_count + 1) if idx not in retry_by_repeat]
    if missing_repeats:
        raise SystemExit(f"Missing retry rows for repeat_index={missing_repeats}")

    args.backup.parent.mkdir(parents=True, exist_ok=True)
    args.backup.write_bytes(args.main.read_bytes())

    replaced = 0
    merged_rows: list[dict] = []
    for row in main_rows:
        if row.get("task_id") == args.task_id and row.get("mode") == args.mode and repeat_index(row) in retry_by_repeat:
            merged_rows.append(retry_by_repeat[repeat_index(row)])
            replaced += 1
        else:
            merged_rows.append(row)
    merged_rows.sort(key=lambda row: (repeat_index(row), str(row.get("mode") or ""), str(row.get("task_id") or "")))
    write_jsonl(args.main, merged_rows)

    if args.summary:
        existing_summary = {}
        if args.summary.exists():
            try:
                existing_summary = json.loads(args.summary.read_text(encoding="utf-8"))
            except Exception:
                existing_summary = {}
        summary = build_summary(merged_rows)
        for key in (
            "run_dir",
            "annotations",
            "classification",
            "classification_dataset_file",
            "model",
            "repeat_count",
            "output_dir",
        ):
            if key in existing_summary:
                summary[key] = existing_summary[key]
        args.summary.write_text(json.dumps(summary, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    status_counts = Counter(row.get("evaluation_status") for row in retry_rows)
    print(json.dumps({"replaced": replaced, "retry_status": dict(status_counts)}, ensure_ascii=False))


if __name__ == "__main__":
    main()
